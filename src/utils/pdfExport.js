import { jsPDF } from 'jspdf';

const PAGE_H = 297;
const MARGIN = 16;
const BOTTOM = 274;

function tokensToText(tokens) {
  if (!tokens || !Array.isArray(tokens)) return '';
  return tokens.map((t) => (t.u ? t.u : (t.t || ''))).join('');
}

export function buildReportData({
  caseInfo,
  evidence,
  reference,
  stages,
  comparison,
  transcript,
  translations,
  appliedLanguage,
  reportMeta,
}) {
  const applied = translations[appliedLanguage];
  return {
    caseId: caseInfo.id,
    caseTitle: caseInfo.title,
    reportId: reportMeta.id,
    generated: reportMeta.generated,
    examiner: reportMeta.examiner,
    lab: reportMeta.lab,
    reviewStatus: reportMeta.reviewStatus,
    evidence,
    reference,
    stages,
    comparison,
    transcript,
    translation: applied,
    limitations: reportMeta.limitations,
  };
}

export function exportReportPdf(data) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  let y = MARGIN;

  const ensure = (h) => {
    if (y + h > BOTTOM) {
      doc.addPage();
      y = 20;
    }
  };

  const rule = (color = [34, 211, 238]) => {
    doc.setDrawColor(...color);
    doc.setLineWidth(0.6);
    doc.line(MARGIN, y, MARGIN + 24, y);
    y += 4;
  };

  const heading = (text) => {
    ensure(14);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(15, 35, 60);
    doc.text(text, MARGIN, y);
    y += 4.5;
    rule();
  };

  const body = (text, opts = {}) => {
    const { size = 9.5, indent = 0, color = [45, 52, 64], style = 'normal' } = opts;
    doc.setFont('helvetica', style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(text, 210 - MARGIN * 2 - indent);
    lines.forEach((line) => {
      ensure(5);
      doc.text(line, MARGIN + indent, y);
      y += 4.8;
    });
  };

  const bullet = (text) => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(45, 52, 64);
    const lines = doc.splitTextToSize(text, 210 - MARGIN * 2 - 6);
    lines.forEach((line, i) => {
      ensure(5);
      doc.text(i === 0 ? `•  ${line}` : `   ${line}`, MARGIN, y);
      y += 4.8;
    });
  };

  const kv = (pairs) => {
    pairs.forEach(([k, v]) => {
      ensure(6);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(100, 110, 125);
      doc.text(k, MARGIN, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(25, 30, 40);
      doc.text(String(v), MARGIN + 52, y);
      y += 5.2;
    });
  };

  // ---- Letterhead ----
  doc.setFillColor(10, 20, 36);
  doc.rect(0, 0, 210, 26, 'F');
  doc.setTextColor(34, 211, 238);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('AUDIO FORENSICS', MARGIN, 12);
  doc.setTextColor(160, 180, 205);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text('Intelligent Audio Evidence Analysis Platform — Academic Prototype', MARGIN, 18);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text(`CASE ${data.caseId}`, 210 - MARGIN, 12, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.text(`REPORT ${data.reportId}`, 210 - MARGIN, 18, { align: 'right' });
  y = 34;

  // Demo banner
  doc.setFillColor(255, 244, 220);
  doc.setDrawColor(240, 170, 60);
  doc.roundedRect(MARGIN, y, 210 - MARGIN * 2, 16, 2, 2, 'FD');
  doc.setTextColor(160, 90, 10);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('PROTOTYPE / DEMO REPORT — REQUIRES EXPERT VALIDATION BEFORE ANY LEGAL USE', MARGIN + 4, y + 6.5);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text(
    'All analysis outputs in this document are simulated mock data generated by a frontend prototype for Experiment No. 5.',
    MARGIN + 4,
    y + 11.5
  );
  y += 22;

  heading('1. Case Reference');
  kv([
    ['Case ID', data.caseId],
    ['Case title', data.caseTitle],
    ['Report ID', data.reportId],
    ['Generated', data.generated],
    ['Laboratory', data.lab],
    ['Examiner', data.examiner],
    ['Review status', data.reviewStatus],
  ]);
  y += 2;

  heading('2. Evidence File Details');
  body('Questioned exhibit', { style: 'bold', size: 9.5 });
  kv([
    ['Reference', data.evidence.ref],
    ['File name', data.evidence.name],
    ['Duration', data.evidence.duration],
    ['Format', data.evidence.format],
    ['Sample rate', data.evidence.sampleRate],
    ['Channels', data.evidence.channels],
    ['SHA-256 (truncated)', data.evidence.hash],
    ['Captured', data.evidence.captured],
  ]);
  y += 1;
  body('Reference voice sample', { style: 'bold', size: 9.5 });
  kv([
    ['Reference', data.reference.ref],
    ['File name', data.reference.name],
    ['Duration', data.reference.duration],
    ['Format', data.reference.format],
    ['Origin', data.reference.origin],
    ['Quality / SNR', `${data.reference.quality} / ${data.reference.snr}`],
  ]);
  y += 2;

  heading('3. Audio Preprocessing Steps');
  ['noise', 'enhance', 'separate'].forEach((key) => {
    const stage = data.stages[key];
    const label = { noise: 'Noise Reduction', enhance: 'Audio Enhancement', separate: 'Speaker Separation' }[key];
    bullet(`${label} — ${stage.status.toUpperCase()} (${stage.progress}%)`);
  });
  y += 2;

  heading('4. Speaker Separation Summary');
  bullet('Diarization returned 2 speaker tracks across 47 speech segments.');
  bullet('Speaker 01 — 02:31 active, 58% talk time, 29 segments, pitch band 112–148 Hz.');
  bullet('Speaker 02 — 01:48 active, 42% talk time, 18 segments, pitch band 164–205 Hz.');
  y += 2;

  heading('5. Comparison Methodology & Illustrative Observations');
  body(
    'Methodology: both samples were passed through a simulated feature pipeline (VAD segmentation, MFCC extraction, pitch/prosody statistics). The indices below are deterministic mock values produced by the prototype — no validated forensic audio engine or trained speaker-recognition model was involved.'
  );
  y += 1;
  if (data.comparison.status === 'done' && data.comparison.result) {
    const r = data.comparison.result;
    r.metrics.forEach((m) => {
      bullet(`${m.name}: ${m.value.toFixed(2)} (illustrative)`);
    });
    bullet(`Composite illustrative index: ${r.composite.toFixed(2)} — ${r.verdictBand}.`);
    body(
      'IMPORTANT: These figures do NOT establish that the questioned and reference samples were produced by the same person or by different persons. No identification conclusion is claimed or implied.',
      { style: 'bold', color: [150, 60, 20] }
    );
  } else {
    body('Comparison pipeline was not executed for this session; see live application for demo run.', {
      color: [150, 60, 20],
    });
  }
  y += 2;

  heading('6. Original Transcript');
  body(
    `Detected language: ${data?.transcript?.originalLanguageLabel || 'auto'} · ${data?.transcript?.sourceFormat || 'Whisper Automatic Speech Recognition'}`,
    { color: [100, 110, 125] }
  );
  (data?.transcript?.segments || []).forEach((seg) => {
    const txt = seg.tokens ? tokensToText(seg.tokens) : (seg.text || seg.text_src || '');
    bullet(`[${seg.time || '00:00'}] ${seg.speaker || 'SPK'}: ${txt}`);
  });
  y += 2;

  heading(`7. Translation (${data.translation.label || 'English'})`);
  if (data.translation.note) body(data.translation.note, { color: [100, 110, 125] });
  (data.translation.segments || []).forEach((seg) => {
    const txt = seg.tokens ? tokensToText(seg.tokens) : (seg.text || seg.text_src || '');
    bullet(`[${seg.time || '00:00'}] ${seg.speaker || 'SPK'}: ${txt}`);
  });
  y += 2;

  heading('8. Limitations');
  data.limitations.forEach((l) => bullet(l));
  y += 2;

  heading('9. Examiner Review & Conclusion');
  kv([
    ['Status', data.reviewStatus],
    ['Examiner', data.examiner || 'Certified Examiner'],
    ['Uncertain tokens', 'Manual acoustic-phonetic cross-check performed'],
    ['Examiner signature', '__________________________'],
    ['Date', data.generated || '__________________________'],
  ]);
  y += 2;

  heading('10. Certificate u/s 65B Indian Evidence Act / Section 63 BSA 2023');
  body(
    'Part-A: The electronic exhibit stated above was hashed immediately upon receipt with SHA-256. The original record was preserved read-only without alteration, and all analysis was conducted on verified working copies.',
    { size: 8.5 }
  );
  body(
    `Part-B: I, ${data.examiner || 'Examiner'}, certify that this electronic output was produced by the automated forensic audio system during the ordinary course of official examination, with immutable audit logging enabled.`,
    { size: 8.5, style: 'bold' }
  );
  y += 2;

  // Footer + watermark on every page
  const pages = doc.getNumberOfPages();
  const isApproved = String(data.reviewStatus || '').toLowerCase().includes('approved') || String(data.reviewStatus || '').toLowerCase().includes('certified');
  for (let p = 1; p <= pages; p += 1) {
    doc.setPage(p);
    doc.setTextColor(228, 232, 238);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(36);
    doc.text(isApproved ? 'COURT EXHIBIT' : 'PROTOTYPE — DEMO', 105, 165, { align: 'center', angle: 32 });
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(130, 140, 155);
    doc.text(
      isApproved ? 'Certified Forensic Audio Record · Admissible u/s 65B IEA / 63 BSA 2023' : 'Generated by the AUDIO FORENSICS platform · Demonstration / Review Copy',
      105,
      288,
      { align: 'center' }
    );
    doc.text(`Page ${p} of ${pages}`, 210 - MARGIN, 288, { align: 'right' });
  }

  doc.save(`${data.caseId}_${data.reportId}_DEMO.pdf`);
}
