import { useEffect, useRef, useState } from 'react';
import { Activity, AlertTriangle, Loader2 } from 'lucide-react';
import { computeSpectrogram, spectrogramColor } from '../utils/audioAnalysis';
import { formatDuration } from '../utils/format';

export default function SpectrogramView({
  audioBuffer,
  imageUrl,
  title = 'Spectrogram',
  duration = 0,
  height = 230,
  active = true,
}) {
  const wrapRef = useRef(null);
  const canvasRef = useRef(null);
  const [width, setWidth] = useState(0);
  const [imageFailed, setImageFailed] = useState(false);
  const [computing, setComputing] = useState(false);

  useEffect(() => {
    setImageFailed(false);
  }, [imageUrl]);

  useEffect(() => {
    const wrap = wrapRef.current;
    if (!wrap) return undefined;
    const observer = new ResizeObserver((entries) => {
      setWidth(entries[0]?.contentRect?.width || 0);
    });
    observer.observe(wrap);
    setWidth(wrap.getBoundingClientRect().width);
    return () => observer.disconnect();
  }, [audioBuffer, imageUrl]);

  const showCanvas = !imageUrl || imageFailed;

  useEffect(() => {
    if (!showCanvas || !active || !audioBuffer || !width) return undefined;
    const canvas = canvasRef.current;
    if (!canvas) return undefined;
    setComputing(true);
    const timer = window.setTimeout(() => {
      const plotWidth = Math.max(280, Math.floor(width - 54));
      const plotHeight = height;
      const dpr = Math.min(2, window.devicePixelRatio || 1);
      canvas.width = Math.round((plotWidth + 54) * dpr);
      canvas.height = Math.round((plotHeight + 28) * dpr);
      canvas.style.width = `${plotWidth + 54}px`;
      canvas.style.height = `${plotHeight + 28}px`;
      const ctx = canvas.getContext('2d');
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.clearRect(0, 0, plotWidth + 54, plotHeight + 28);

      const spectrogram = computeSpectrogram(audioBuffer, {
        maxWidth: plotWidth,
        height: plotHeight,
        maxFrequency: 8000,
      });
      if (!spectrogram) {
        setComputing(false);
        return;
      }
      const image = ctx.createImageData(spectrogram.width, spectrogram.height);
      for (let i = 0; i < spectrogram.data.length; i += 1) {
        const [r, g, b] = spectrogramColor(spectrogram.data[i]);
        image.data[i * 4] = r;
        image.data[i * 4 + 1] = g;
        image.data[i * 4 + 2] = b;
        image.data[i * 4 + 3] = 255;
      }
      const offscreen = document.createElement('canvas');
      offscreen.width = spectrogram.width;
      offscreen.height = spectrogram.height;
      offscreen.getContext('2d').putImageData(image, 0, 0);
      ctx.imageSmoothingEnabled = true;
      ctx.drawImage(offscreen, 54, 0, plotWidth, plotHeight);

      ctx.strokeStyle = 'rgba(248, 245, 239, 0.2)';
      ctx.fillStyle = 'rgba(248, 245, 239, 0.82)';
      ctx.font = '10px "JetBrains Mono", monospace';
      ctx.lineWidth = 1;
      for (let i = 0; i <= 4; i += 1) {
        const y = (i / 4) * plotHeight;
        ctx.beginPath();
        ctx.moveTo(54, y);
        ctx.lineTo(54 + plotWidth, y);
        ctx.stroke();
        const freq = spectrogram.maxFrequency * (1 - i / 4);
        ctx.fillText(`${(freq / 1000).toFixed(0)}k`, 8, y + 3);
      }
      for (let i = 0; i <= 4; i += 1) {
        const x = 54 + (i / 4) * plotWidth;
        ctx.beginPath();
        ctx.moveTo(x, 0);
        ctx.lineTo(x, plotHeight);
        ctx.stroke();
        const time = (spectrogram.duration || duration) * (i / 4);
        ctx.fillText(formatDuration(time), Math.min(54 + plotWidth - 28, x + 4), plotHeight + 18);
      }
      setComputing(false);
    }, 20);

    return () => window.clearTimeout(timer);
  }, [showCanvas, active, audioBuffer, width, height, duration]);

  if (!imageUrl && !audioBuffer) {
    return (
      <div className="spectrogram-empty">
        <Activity size={18} aria-hidden="true" />
        <p>No spectrogram is available for this source.</p>
        <span>Processed spectrograms are generated by the backend analysis run.</span>
      </div>
    );
  }

  return (
    <figure className="spectrogram-figure">
      <div ref={wrapRef} className="spectrogram-canvas-wrap">
        {imageUrl && !imageFailed ? (
          <img
            src={imageUrl}
            alt={title}
            className="spectrogram-image"
            onError={() => setImageFailed(true)}
          />
        ) : (
          <canvas ref={canvasRef} className="spectrogram-canvas" aria-label={title} role="img" />
        )}
        {computing && showCanvas && (
          <span className="spectrogram-status">
            <Loader2 size={14} className="spin" /> Computing FFT…
          </span>
        )}
        {imageFailed && !audioBuffer && (
          <span className="spectrogram-status error">
            <AlertTriangle size={14} /> Spectrogram image is unavailable.
          </span>
        )}
      </div>
      <figcaption>
        {imageUrl && !imageFailed
          ? `${title} · rendered by the analysis backend`
          : `${title} · computed in this browser from the decoded audio`}
      </figcaption>
    </figure>
  );
}
